import sharp from 'sharp'
import { mkdir, stat, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = path.join(root, 'assets/lift')
const sources = ['2.jpeg', '3.jpeg', '54.jpeg', '85.jpg', '89.jpeg', '102.jpg', '110.jpeg']
await mkdir(output, { recursive: true })

const imports = []
const slides = []
let originalBytes = 0
let optimizedBytes = 0

for (const [index, filename] of sources.entries()) {
  const source = path.join(root, 'assets', filename)
  const name = `${path.parse(filename).name}.webp`
  // Cards are at most 280 CSS pixels wide; 560px also covers Retina displays.
  const { data, info } = await sharp(source).rotate()
    .resize({ width: 560, withoutEnlargement: true })
    .webp({ quality: 80, effort: 6 }).toBuffer({ resolveWithObject: true })
  const preview = await sharp(source).rotate().resize({ width: 24 })
    .webp({ quality: 35 }).toBuffer()
  const smallName = `${path.parse(filename).name}-280.webp`
  const small = await sharp(source).rotate().resize({ width: 280, withoutEnlargement: true })
    .webp({ quality: 82, effort: 6 }).toBuffer()

  await writeFile(path.join(output, name), data)
  await writeFile(path.join(output, smallName), small)
  imports.push(`import slide${index} from './${name}'`)
  imports.push(`import slide${index}Small from './${smallName}'`)
  slides.push(`  { src: slide${index}Small, srcset: slide${index}Small + ' 280w, ' + slide${index} + ' ${info.width}w', width: ${info.width}, height: ${info.height}, preview: 'data:image/webp;base64,${preview.toString('base64')}' }`)
  originalBytes += (await stat(source)).size
  optimizedBytes += data.length
  console.log(`${filename}: ${data.length} bytes (${info.width}x${info.height})`)
}

await writeFile(path.join(output, 'slides.js'),
  `// Generated by npm run optimize:lift-images. Keep original photos in assets/.\n${imports.join('\n')}\n\nexport const liftSlides = [\n${slides.join(',\n')},\n]\n`)
console.log(`Total: ${originalBytes} -> ${optimizedBytes} bytes (${(100 * (1 - optimizedBytes / originalBytes)).toFixed(1)}% smaller)`)

import sharp from 'sharp'
import { mkdir, stat, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = path.join(root, 'assets/led-indoor')
const groups = {
  greenCityImages: [
    '17ef9906-9cdd-4b48-9bf8-88f83451272d.jpg',
    '42790fe6-3191-4be3-85bb-18854ffab0e2.jpg',
    '77180d35-0438-4b2f-a29c-2b4b6c955cae.jpg',
    'b063d9b5-bbb5-4a42-bc6d-4bc2b11cd683.jpg',
  ],
  tairImages: ['tair2.png', 'tair1.png', 'tair4.png', 'tair5.png', 'tair3.png'],
}
await mkdir(output, { recursive: true })

const imports = []
const variants = []
const exports = []
let originalBytes = 0
let smallBytes = 0
let largeBytes = 0
let index = 0

for (const [group, filenames] of Object.entries(groups)) {
  const images = []
  for (const filename of filenames) {
    const source = path.join(root, 'public/exampleled', filename)
    const name = path.parse(filename).name
    const sizes = []
    // Cards are at most 340 CSS pixels wide. Keep a 2x version for Retina.
    for (const width of [360, 680]) {
      const { data, info } = await sharp(source).rotate()
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: 82, effort: 6 }).toBuffer({ resolveWithObject: true })
      const asset = `${name}-${width}.webp`
      await writeFile(path.join(output, asset), data)
      imports.push(`import image${index}_${width} from './${asset}'`)
      sizes.push(info)
      if (width === 360) smallBytes += data.length
      else largeBytes += data.length
    }
    images.push(`image${index}_360`)
    variants.push(`  [image${index}_360]: { srcset: image${index}_360 + ' ${sizes[0].width}w, ' + image${index}_680 + ' ${sizes[1].width}w', width: ${sizes[1].width}, height: ${sizes[1].height} }`)
    originalBytes += (await stat(source)).size
    console.log(`${filename}: 360px ${sizes[0].size} bytes; 680px ${sizes[1].size} bytes`)
    index++
  }
  exports.push(`export const ${group} = [${images.join(', ')}]`)
}

await writeFile(path.join(output, 'images.ts'),
  `// Generated by npm run optimize:indoor-images. Originals remain in public/exampleled/.\n${imports.join('\n')}\n\n${exports.join('\n')}\n\nexport const indoorImageSources: Record<string, { srcset: string; width: number; height: number }> = {\n${variants.join(',\n')},\n}\n`)
console.log(`Total: ${originalBytes} -> ${smallBytes} bytes (360px), ${largeBytes} bytes (680px); ${(100 * (1 - largeBytes / originalBytes)).toFixed(1)}% smaller even at 2x`)

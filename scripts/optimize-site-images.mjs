import sharp from 'sharp'
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const report = []

async function generate(group, sources, exportName) {
  const output = path.join(root, 'assets/optimized', group)
  await mkdir(output, { recursive: true })
  const imports = []
  const entries = []
  for (const [index, { file, widths, quality = 84, lossless = false }] of sources.entries()) {
    const source = path.join(root, 'assets', file)
    const original = await readFile(source)
    const metadata = await sharp(source, { density: 144 }).metadata()
    const actualWidths = [...new Set(widths.map(width => Math.min(width, metadata.width)))].sort((a, b) => a - b)
    const variants = []
    for (const width of actualWidths) {
      let { data, info } = await sharp(source, { density: 144 }).rotate()
        .resize({ width, withoutEnlargement: true })
        .webp({ quality, lossless, effort: 6 }).toBuffer({ resolveWithObject: true })
      // Do not recompress an existing WebP into a larger file at the same size.
      if (metadata.format === 'webp' && info.width === metadata.width && info.height === metadata.height && original.length < data.length) data = original
      const name = `${path.parse(file).name}-${width}.webp`
      await writeFile(path.join(output, name), data)
      const variable = `image${index}_${width}`
      imports.push(`import ${variable} from './${name}'`)
      variants.push({ variable, width: info.width, height: info.height, bytes: data.length })
    }
    const largest = variants.at(-1)
    entries.push(`  ${JSON.stringify(file)}: { src: ${variants[0].variable}, srcset: ${variants.map(v => `${v.variable} + ' ${v.width}w'`).join(" + ', ' + ")}, width: ${largest.width}, height: ${largest.height} }`)
    report.push({ group, source: file, originalBytes: (await stat(source)).size, variants: variants.map(({ variable, ...v }) => v) })
  }
  await writeFile(path.join(output, 'images.ts'), `// Generated by npm run optimize:images; keep originals in assets/.\n${imports.join('\n')}\n\nexport const ${exportName} = {\n${entries.join(',\n')},\n}\n`)
}

await generate('outdoor', [
  ...Array.from({ length: 13 }, (_, i) => ({ file: `led-screens${i + 1}.png`, widths: [360, 680, 1024] })),
  { file: 'led-yubileyny.webp', widths: [640, 1200, 1600], quality: 88 },
], 'outdoorImages')

await generate('content', [
  ...[1, 2, 3, 4, 5].map(i => ({ file: `${i}b.webp`, widths: [360, 720, 1280], quality: 86 })),
  { file: 'formats-mock.png', widths: [320, 461], quality: 88 },
  ...['otz1.jpeg', 'otz2.jpeg'].map(file => ({ file, widths: [360, 720, 1200], quality: 90 })),
  ...Array.from({ length: 9 }, (_, i) => ({ file: `${i + 1}.webp`, widths: [280, 560], quality: 86 })),
  ...['button', 'hand', 'medal', 'money', 'people', 'sale', 'staff'].map(name => ({ file: `${name}.png`, widths: [160, 250], quality: 90 })),
  { file: 'svg/loggo.svg', widths: [240, 480, 960], lossless: true },
  { file: 'svg/howled.webp', widths: [640, 1280], quality: 88 },
], 'contentImages')

// Render logos at up to 2x their displayed size, preserving transparency.
const partners = (await readdir(path.join(root, 'assets/partners'))).filter(f => /\.(svg|png|jpe?g|webp)$/i.test(f)).sort((a, b) => a.localeCompare(b, 'en'))
await generate('partners', partners.map(file => ({ file: `partners/${file}`, widths: [192, 384], lossless: true })), 'partnerImages')
await writeFile(path.join(root, 'assets/optimized/report.json'), JSON.stringify(report, null, 2) + '\n')
for (const group of ['outdoor', 'content', 'partners']) {
  const rows = report.filter(r => r.group === group)
  const before = rows.reduce((n, r) => n + r.originalBytes, 0)
  const after = rows.reduce((n, r) => n + r.variants[Math.min(1, r.variants.length - 1)].bytes, 0)
  console.log(`${group}: ${rows.length} images, ${before} -> ${after} bytes (${(100 * (1 - after / before)).toFixed(1)}% smaller at 2x)`)
}
